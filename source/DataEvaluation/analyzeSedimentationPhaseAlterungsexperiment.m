function toBoundTimePlot(types,boundTimesSummaryS,boundTimeEdges,colors,label,fit,startFitLater)
    set(gcf,'Position',[209,188,681,778]);
    for i=1:size(types,2)
        subplot(size(types,2)+2,1,i+1);
        boundTimesS=boundTimesSummaryS(types{1,i});
        boundTimesS(isinf(boundTimesS))=650;
        h=histogram(boundTimesS,'BinEdges',boundTimeEdges,'Normalization','pdf','FaceColor',colors(i,:),'EdgeColor',colors(i,:)./2,'FaceAlpha',1,'EdgeAlpha',1);
        hold(gca,'on');
        valErrors=sqrt(h.BinCounts)./sum(h.BinCounts)./diff(boundTimeEdges);
        binCenters=diff(boundTimeEdges)/2+boundTimeEdges(1:(end-1));
        erb=errorbar(binCenters,h.Values,valErrors);
        erb.Color = [0 0 0];                            
        erb.LineStyle = 'none';
        
        if fit
            fitter=FitterPlain();
            model=ExponentialModel();
            model.setFixedParameters([NaN,NaN,0]);
            fitter.setModel(model);
            fitter.setErrorAnalysisIterCount(1000);
            if startFitLater
                fitter.setData(binCenters(2:(end-1))',h.Values(2:(end-1))',[],valErrors(2:(end-1))');
            else
                fitter.setData(binCenters(1:(end-1))',h.Values(1:(end-1))',[],valErrors(1:(end-1))');
            end
            fun=fitter.getModelFunWParams();
            param=fitter.getResultParameters();
            paramErrors=fitter.getResultParameterErrors();
            plot(binCenters,fun(binCenters),'Color','k');
        end
        
        ylim([0,0.05]);
        if i~=size(types,2)
            set(gca,'XTick',[]);
        else
            xlabel(label);
        end
        %set(gca,'YTick',0:0.01:0.05);
        set(gca,'YScale','log');
        ylim(gca,[1E-5,1E-1]);
        set(gca,'YTick',[1E-5,1E-4,1E-3,1E-2,1E-1]);
        if i~=1
            set(gca,'YTickLabel',[]);
        else
            ylabel('pdf');
        end
        if fit
            title([types{1,i},', k_off=(',num2str(-1/param(2),'%.3f'),177,num2str(paramErrors(2)./(param(2)^2),'%.3f'),')/s'],'Interpreter','none','Position',[330.8772246733956,0.01,1.4210854715202e-14]);
        else
            title(types{1,i},'Interpreter','none','Position',[330.8772246733956,0.01,1.4210854715202e-14]);
        end
    end
end

function toBarPlot(ax,types,mapCells,mapErrors,colors,showLabels)
    vals=NaN(size(types));
    valErrors=NaN(size(types));
    for i=1:size(types,2)
        vals(1,i)=mapCells(types{1,i});
        if ~isempty(mapErrors)
            valErrors(1,i)=mapErrors(types{1,i});
        end
    end
    hold(gca,'on');
    b=bar(reordercats(categorical(types),types),vals','FaceColor','flat');
    b.CData=colors;
    
    ebp=errorbar(reordercats(categorical(types),types),vals',valErrors');
    ebp.Color = [0 0 0];                            
    ebp.LineStyle = 'none';  
    hold(gca,'off');
    if showLabels
    else
        set(gca,'XTick',[]);
    end
end

