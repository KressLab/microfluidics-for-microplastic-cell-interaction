    immobileFractionCellErrorSummary(BEAD_TYPES{1,i})=immobileFractionCellError;
    
    unstickyFractionCell=sum(isinf(unboundTimesCellSSummary(BEAD_TYPES{1,i})))/length(unboundTimesCellSSummary(BEAD_TYPES{1,i}));
